// Worker CPU report (S-019, risk T3, NFR-009): summarises CPU samples per hot path and
// writes docs/architecture/cpu-measurements.md. Pure; scripts/cpu-report.ts does the I/O.

/** Free Workers plan CPU limit per request. */
export const CPU_LIMIT_MS = 10;

export const HOT_PATHS = [
  { id: "checkout-submit", label: "Checkout submit (`POST /basket`)" },
  { id: "basket", label: "Basket with price calculation (`GET /basket`)" },
  { id: "tracking", label: "Tracking page (`GET /t/:token`)" },
] as const;

export type HotPathId = (typeof HOT_PATHS)[number]["id"];
export type Phase = "cold" | "warm";
export type Verdict = "pass" | "fail";

export interface CpuSummary {
  count: number;
  p50: number;
  p99: number;
  max: number;
  verdict: Verdict;
}

export class EmptySamplesError extends Error {
  constructor() {
    super("No CPU samples to summarise");
    this.name = "EmptySamplesError";
  }
}

const round = (ms: number) => Math.round(ms * 1000) / 1000;

/** Nearest-rank percentile of an ascending list. */
function nearestRank(sorted: readonly number[], percent: number): number {
  return sorted[Math.max(1, Math.ceil((percent / 100) * sorted.length)) - 1]!;
}

export function summarizeCpu(samples: readonly number[]): CpuSummary {
  if (samples.length === 0) throw new EmptySamplesError();
  const sorted = [...samples].sort((a, b) => a - b);
  const p99 = round(nearestRank(sorted, 99));
  return {
    count: sorted.length,
    p50: round(nearestRank(sorted, 50)),
    p99,
    max: round(sorted.at(-1)!),
    verdict: p99 < CPU_LIMIT_MS ? "pass" : "fail",
  };
}

export interface HotPathResult {
  path: HotPathId;
  cold: readonly number[];
  warm: readonly number[];
}

export interface CpuReportInput {
  /** Measurement date (YYYY-MM-DD), or null before the first measurement. */
  date: string | null;
  environment: string;
  results: readonly HotPathResult[];
}

type Overall = "PASS" | "FAIL" | "PENDING";

function phaseRow(label: string, samples: readonly number[] | undefined): { row: string; verdict: Verdict | null } {
  if (!samples || samples.length === 0) return { row: `| ${label} | 0 | - | - | - | not measured |`, verdict: null };
  const s = summarizeCpu(samples);
  return { row: `| ${label} | ${s.count} | ${s.p50} | ${s.p99} | ${s.max} | ${s.verdict === "fail" ? "FAIL" : "pass"} |`, verdict: s.verdict };
}

function overallOf(verdicts: readonly (Verdict | null)[]): Overall {
  if (verdicts.includes("fail")) return "FAIL";
  return verdicts.includes(null) ? "PENDING" : "PASS";
}

const HAND_OFF = [
  "**Owner decision needed.** At least one hot path has p99 CPU at or above 10 ms, the free",
  "plan's limit. Options: reduce the work on that path, or move to Workers Paid ($5/month),",
  "which breaks NFR-009 (Rs 0 running cost). Nothing has been bought or configured.",
].join("\n");

export function renderCpuReport({ date, environment, results }: CpuReportInput): string {
  const verdicts: (Verdict | null)[] = [];
  const sections = HOT_PATHS.map((path) => {
    const result = results.find((r) => r.path === path.id);
    const cold = phaseRow("Cold", result?.cold);
    const warm = phaseRow("Warm", result?.warm);
    verdicts.push(cold.verdict, warm.verdict);
    return [`### ${path.label}`, "", "| Phase | Count | p50 (ms) | p99 (ms) | Max (ms) | Verdict |", "|---|---|---|---|---|---|", cold.row, warm.row].join("\n");
  });
  const overall = overallOf(verdicts);
  return [
    "# Worker CPU measurements (risk T3, NFR-009)",
    "",
    "Generated by `npm run cpu:report` (`src/app/lib/cpu-report.ts`); procedure in",
    "`docs/runbooks/worker-cpu.md`. Target: p99 CPU under 10 ms per request (free Workers plan),",
    "at least 50 warm requests per hot path. Percentiles are nearest-rank.",
    "",
    `Measured: ${date ? `${date} on ${environment}` : "not yet"}`,
    "",
    `Overall: ${overall}`,
    ...(overall === "FAIL" ? ["", HAND_OFF] : []),
    "",
    "## Results",
    "",
    sections.join("\n\n"),
    "",
  ].join("\n");
}

export interface CpuSample {
  path: HotPathId;
  phase: Phase;
  cpuMs: number;
}

/** Which hot path a measured request belongs to; the load script tags URLs with `?cpu=cold|warm`. */
export function classifyHotPath(method: string, url: string): { path: HotPathId; phase: Phase } | null {
  const parsed = new URL(url);
  const phase = parsed.searchParams.get("cpu");
  if (phase !== "cold" && phase !== "warm") return null;
  const pathname = parsed.pathname.replace(/^\/fr(?=\/)/, "");
  const upper = method.toUpperCase();
  if (pathname === "/basket") return { path: upper === "POST" ? "checkout-submit" : "basket", phase };
  if (upper === "GET" && /^\/t\/[^/]+$/.test(pathname)) return { path: "tracking", phase };
  return null;
}

interface LogRecord {
  cpuTime?: number;
  cpuTimeMs?: number;
  event?: { request?: { method?: string; url?: string } };
  $workers?: { cpuTimeMs?: number; event?: { request?: { method?: string; url?: string } } };
}

function sampleFromRecord(record: LogRecord): CpuSample | null {
  const cpuMs = record.cpuTime ?? record.cpuTimeMs ?? record.$workers?.cpuTimeMs;
  const request = record.event?.request ?? record.$workers?.event?.request;
  if (typeof cpuMs !== "number" || !request?.url) return null;
  const hit = classifyHotPath(request.method ?? "GET", request.url);
  return hit ? { ...hit, cpuMs } : null;
}

function parseCsv(text: string): CpuSample[] {
  const ids = new Set<string>(HOT_PATHS.map((p) => p.id));
  return text
    .split("\n")
    .slice(1)
    .map((line) => line.trim().split(","))
    .filter(([path, phase, ms]) => ids.has(path ?? "") && (phase === "cold" || phase === "warm") && Number.isFinite(Number(ms)) && ms !== "")
    .map(([path, phase, ms]) => ({ path: path as HotPathId, phase: phase as Phase, cpuMs: Number(ms) }));
}

/**
 * CPU samples from a CSV (`path,phase,cpu_ms`, typed from the dashboard) or from JSON
 * (one object per line, pretty-printed objects one after another, or an array) as printed by `wrangler tail --format json` or a
 * Workers Logs export. Requests that are not tagged hot paths are skipped.
 */
export function parseCpuSamples(text: string): CpuSample[] {
  const trimmed = text.trim();
  if (trimmed.startsWith("path,")) return parseCsv(trimmed);
  return (parseJsonStream(trimmed) as LogRecord[]).map(sampleFromRecord).filter((s): s is CpuSample => s !== null);
}

/** Groups parsed samples into report input rows. */
export function groupSamples(samples: readonly CpuSample[]): HotPathResult[] {
  return HOT_PATHS.map(({ id }) => ({
    path: id,
    cold: samples.filter((s) => s.path === id && s.phase === "cold").map((s) => s.cpuMs),
    warm: samples.filter((s) => s.path === id && s.phase === "warm").map((s) => s.cpuMs),
  }));
}

/** Samples as `path,phase,cpu_ms` CSV: the evidence that is committed (raw logs carry URLs). */
export function samplesCsv(samples: readonly CpuSample[]): string {
  return ["path,phase,cpu_ms", ...samples.map((s) => `${s.path},${s.phase},${s.cpuMs}`)].join("\n") + "\n";
}

/** End index (exclusive) of the JSON object or array that opens at `start`, or -1 if unbalanced. */
function balancedEnd(text: string, start: number): number {
  let depth = 0;
  let inString = false;
  for (let i = start; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      if (ch === "\\") i += 1;
      else if (ch === '"') inString = false;
    } else if (ch === '"') inString = true;
    else if (ch === "{" || ch === "[") depth += 1;
    else if (ch === "}" || ch === "]") {
      depth -= 1;
      if (depth === 0) return i + 1;
    }
  }
  return -1;
}

/** Parses the balanced value at `start` into `values`; returns where scanning resumes. */
function pushParsed(text: string, start: number, values: unknown[]): number {
  const end = balancedEnd(text, start);
  if (end < 0) return start + 1;
  try {
    const value: unknown = JSON.parse(text.slice(start, end));
    values.push(...(Array.isArray(value) ? value : [value]));
    return end;
  } catch {
    return start + 1;
  }
}

/**
 * Every JSON object in `text`: newline-delimited, pretty-printed one after another (as
 * `wrangler tail --format json` prints them), or inside a top-level array. Banner lines and
 * malformed or truncated objects (a tail killed mid-write) are skipped.
 */
export function parseJsonStream(text: string): unknown[] {
  const values: unknown[] = [];
  let i = text.search(/[{[]/);
  while (i >= 0 && i < text.length) {
    i = pushParsed(text, i, values);
    const next = text.slice(i).search(/[{[]/);
    i = next < 0 ? -1 : i + next;
  }
  return values.filter((v) => typeof v === "object" && v !== null);
}

// ---- Job summary for the cpu-measure workflow (S-019): CPU per route from `wrangler tail`. ----

/** Same rule as workers/log-redact.ts (kept import-free so Node runs this file directly). */
const TOKEN_PATH = /^((?:\/fr)?\/(?:t|order)\/)[^/]+/i;

/** `METHOD /path` with bearer tokens redacted and no query string or host, or null. */
export function routeName(method: string | undefined, url: string | undefined): string | null {
  if (!url) return null;
  let pathname: string;
  try {
    pathname = new URL(url).pathname;
  } catch {
    return null;
  }
  return `${(method ?? "GET").toUpperCase()} ${pathname.replace(TOKEN_PATH, "$1[redacted]")}`;
}

/** Text safe to print from wrangler's own messages: URLs lose their query and token. */
export function redactText(text: string): string {
  return text
    .replace(/(\/(?:t|order)\/)[^/\s?#"']+/gi, "$1[redacted]")
    .replace(/\?[^\s"']*/g, "")
    .replace(/\b(token|authorization|bearer)([=:\s]+)(?:bearer\s+)?[^\s;,]+/gi, "$1$2[redacted]");
}

export interface RouteCpu {
  route: string;
  hotPath: HotPathId | null;
  cpuMs: number[];
  /** Invocations Cloudflare stopped for exceeding the CPU limit (`outcome: exceededCpu`). */
  exceeded: number;
}

interface TailEvent {
  cpuTime?: unknown;
  outcome?: unknown;
  event?: { request?: { method?: string; url?: string } };
}

const HOT_ROUTE: Record<HotPathId, string> = {
  "checkout-submit": "POST /basket",
  basket: "GET /basket",
  tracking: "GET /t/[redacted]",
};

/** Groups tail events by route; tagged (`?cpu=`) hot-path requests are kept apart from other traffic. */
export function cpuByRoute(text: string): RouteCpu[] {
  const rows = new Map<string, RouteCpu>(HOT_PATHS.map(({ id }) => [id, { route: HOT_ROUTE[id], hotPath: id, cpuMs: [], exceeded: 0 }]));
  for (const record of parseJsonStream(text) as TailEvent[]) {
    const request = record.event?.request;
    const route = routeName(request?.method, request?.url);
    if (!route || typeof record.cpuTime !== "number") continue;
    const hot = classifyHotPath(request?.method ?? "GET", request!.url!)?.path ?? null;
    const key = hot ?? `other ${route}`;
    const row = rows.get(key) ?? { route, hotPath: null, cpuMs: [], exceeded: 0 };
    row.cpuMs.push(record.cpuTime);
    if (record.outcome === "exceededCpu") row.exceeded += 1;
    rows.set(key, row);
  }
  return [...rows.values()];
}

export interface RouteSummary {
  route: string;
  hotPath: HotPathId | null;
  count: number;
  p50: number | null;
  p95: number | null;
  p99: number | null;
  max: number | null;
  exceeded: number;
  verdict: Verdict | "no samples" | "info";
}

export function summarizeRoute({ route, hotPath, cpuMs, exceeded }: RouteCpu): RouteSummary {
  if (cpuMs.length === 0) return { route, hotPath, count: 0, p50: null, p95: null, p99: null, max: null, exceeded, verdict: hotPath ? "no samples" : "info" };
  const sorted = [...cpuMs].sort((a, b) => a - b);
  const p99 = round(nearestRank(sorted, 99));
  const failed = p99 >= CPU_LIMIT_MS || exceeded > 0;
  return {
    route,
    hotPath,
    count: sorted.length,
    p50: round(nearestRank(sorted, 50)),
    p95: round(nearestRank(sorted, 95)),
    p99,
    max: round(sorted.at(-1)!),
    exceeded,
    verdict: hotPath ? (failed ? "fail" : "pass") : "info",
  };
}

/** 1 when a hot path fails or has no samples (nothing proves it fits), else 0. */
export function measureExitCode(summaries: readonly RouteSummary[]): 0 | 1 {
  return summaries.some((s) => s.hotPath && (s.verdict === "fail" || s.verdict === "no samples")) ? 1 : 0;
}

export interface JobSummaryInput {
  summaries: readonly RouteSummary[];
  phase: Phase;
  rounds: number;
  host: string;
}

const cell = (n: number | null) => (n === null ? "-" : String(n));
const VERDICT_CELL = { pass: "pass", fail: "**FAIL**", "no samples": "**no samples**", info: "(not a hot path)" } as const;

/** Markdown for `$GITHUB_STEP_SUMMARY`: route names only, never URLs, queries or tokens. */
export function renderJobSummary({ summaries, phase, rounds, host }: JobSummaryInput): string {
  const failed = measureExitCode(summaries) === 1;
  const rows = summaries.map(
    (s) => `| \`${s.route}\` | ${s.count} | ${cell(s.p50)} | ${cell(s.p95)} | ${cell(s.p99)} | ${cell(s.max)} | ${s.exceeded} | ${VERDICT_CELL[s.verdict]} |`,
  );
  return [
    "## Worker CPU per route (S-019, risk T3)",
    "",
    `${host}, phase ${phase}, ${rounds} rounds. CPU time per invocation from \`wrangler tail\`; nearest-rank percentiles in ms.`,
    `A hot path fails when p99 is at or above ${CPU_LIMIT_MS} ms (free Workers plan) or any invocation exceeded the CPU limit.`,
    "",
    "| Route | Count | p50 | p95 | p99 | Max | Exceeded CPU | Verdict |",
    "|---|---|---|---|---|---|---|---|",
    ...rows,
    "",
    failed
      ? "**Result: FAIL.** A hot path is over the limit or has no samples. If over: the Owner decides (reduce the work, or Workers Paid at $5/month, which breaks NFR-009)."
      : "**Result: PASS.** Every hot path's p99 is under the limit.",
    "",
  ].join("\n");
}

/** A request the load script gave up on (epoch ms), written by scripts/cpu-load.ts. */
/** A request that timed out (no `status`) or answered outside 2xx/3xx (`status` set). */
export interface TimedOutRequest {
  route: string;
  startedAt: number;
  endedAt: number;
  status?: number;
}

interface DiagnosticEvent extends TailEvent {
  eventTimestamp?: unknown;
  event?: TailEvent["event"] & { response?: { status?: unknown } };
  exceptions?: { name?: unknown; message?: unknown }[];
  logs?: { level?: unknown; message?: unknown[] }[];
}

/** redactText plus connection strings, emails and phone numbers (error messages may carry them). */
export function redactDiagnostic(text: string): string {
  return redactText(
    text
      .replace(/\b[a-z][a-z0-9+.-]*:\/\/[^\s"'@/]*@[^\s"']+/gi, "[redacted-url]")
      .replace(/\b(host|user|password)=\S+/gi, "$1=[redacted]")
      .replace(/[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, "[redacted-email]")
      .replace(/\+?\d[\d ()-]{6,}\d/g, "[redacted-number]"),
  );
}

/**
 * For each failed request (timed out, or answered outside 2xx/3xx): the tail events of the same
 * route inside its window, with outcome, response status, exception names/messages and
 * error/warn log lines (all redacted). Empty when nothing failed; says so when no event
 * matches, so a recurrence is diagnosable.
 */
export function timeoutDiagnostics(tailText: string, timeouts: readonly TimedOutRequest[]): string {
  if (timeouts.length === 0) return "";
  const events = (parseJsonStream(tailText) as DiagnosticEvent[]).filter((e) => typeof e.eventTimestamp === "number");
  const lines = ["## Failed requests: matching tail events", ""];
  for (const t of timeouts) {
    lines.push(t.status === undefined
      ? `- \`${t.route}\` gave no response within ${Math.round((t.endedAt - t.startedAt) / 1000)} s`
      : `- \`${t.route}\` answered ${t.status}`);
    const matches = events.filter((e) => {
      const at = e.eventTimestamp as number;
      return routeName(e.event?.request?.method, e.event?.request?.url) === t.route && at >= t.startedAt - 2_000 && at <= t.endedAt + 30_000;
    });
    if (matches.length === 0) lines.push("  - no matching tail event");
    for (const e of matches) lines.push(...describeEvent(e));
  }
  return `${lines.join("\n")}\n`;
}

function describeEvent(e: DiagnosticEvent): string[] {
  const cpu = typeof e.cpuTime === "number" ? `, cpu ${e.cpuTime} ms` : "";
  const status = typeof e.event?.response?.status === "number" ? `, response ${e.event.response.status}` : "";
  const lines = [`  - outcome ${redactText(String(e.outcome ?? "unknown"))}${status}${cpu}`];
  for (const x of e.exceptions ?? []) lines.push(`    - exception ${redactDiagnostic(`${String(x.name ?? "")}: ${String(x.message ?? "")}`).slice(0, 1500)}`);
  for (const l of e.logs ?? []) {
    if (l.level === "error" || l.level === "warn") lines.push(`    - ${l.level} ${redactDiagnostic((l.message ?? []).map(String).join(" ")).slice(0, 1500)}`);
  }
  return lines;
}
